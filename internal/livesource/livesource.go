// Package livesource — разбор выдачи внешнего источника live-статусов.
//
// Всё, что специфично для конкретного вендора, живёт здесь: смена источника
// должна быть новым файлом в этом пакете, а не переписыванием ingest'а.
// Ниже по течению не должно остаться ни одного места, знающего имена полей
// вендора.
package livesource

import (
	"context"
	"time"
)

// SourceName — имя источника в external_ids и live_* таблицах.
const SourceName = "livetennisapi"

// State — что источник говорит про матч.
//
// Значения 'scheduled' здесь намеренно НЕТ. Его никто не порождает: расписание
// живёт в live_schedule, а не в наблюдениях. Если бы оно появилось, запись
// такого наблюдения сдвинула бы last_seen_run_id и молча сбросила счётчик
// пропусков живого матча — то есть карточка не погасла бы никогда.
type State string

const (
	StateOnCourt   State = "on_court"
	StateFinished  State = "finished"
	StateSuspended State = "suspended"
)

// Observation — одна строка live-борта, приведённая к нашим понятиям.
//
// Здесь НЕТ и не может быть ни одного поля со счётом: ни сетов, ни геймов, ни
// очков, ни подающего. Это типовая половина правила 1 из
// docs/live-status-ingest.md — карточка показывает факт присутствия на корте,
// а не счёт. Вторая половина в parse.go: структура разбора не описывает
// объект score вовсе, поэтому пронести счёт дальше физически нечем.
type Observation struct {
	// Идентификатор матча у источника.
	ExternalKey string
	// Идентификаторы игроков у источника; резолвятся через external_ids.
	PlayerKeys [2]string
	// Код раунда уже в нашем словаре (F, SF, QF, R16...). Может быть пустым.
	RoundCode string
	// Идентификатор турнира у источника. На live-борте бывает пустым
	// (в срезе — у 9 строк из 19), поэтому опираться на него на live-пути нельзя.
	TournamentKey string
	ScheduledAt   *time.Time
	State         State
	// Сырое event_status: enum вендора уже дрейфует, поэтому храним как есть
	// для логов и для теста, который ловит появление нового значения.
	EventStatus string
}

// Fixture — предстоящий матч наших игроков: из него строится окно опроса,
// а в Phase 8 — и сама строка matches.
type Fixture struct {
	ExternalKey   string
	PlayerKeys    [2]string
	RoundCode     string
	TournamentKey string
	Tournament    string
	// Квалификация. Наши розыгрыши — это ОСНОВНЫЕ сетки (в tournament_entries
	// у US Open 66 заявок, то есть основа), поэтому писатель матчей строки
	// квалификации пропускает: иначе они попадут в чужую сетку и её испортят.
	// На live-пути значение не используется: там матч и так резолвится по
	// участникам, а не по сетке.
	IsQualifying bool
	// null означает, что порядок игры ещё не опубликован.
	//
	// Поля с одной лишь датой здесь СОЗНАТЕЛЬНО нет. Оно есть только в схеме
	// GET /fixtures (event_date, format: date — голое "2026-08-27", которое в
	// time.Time не разбирается), а мы ходим в GET /matches?status=upcoming —
	// единственный эндпоинт с повторяемым фильтром player=, благодаря которому
	// 101 отслеживаемый игрок стоит 3 запроса вместо выкачивания всех фикстур
	// мира. Цена решения: фикстура без scheduled_at окна опроса не открывает.
	// В снятом срезе таких нет ни одной из 200, но полагаться на это нельзя.
	ScheduledAt *time.Time
}

// Board — разобранный live-борт.
type Board struct {
	Observations []Observation
	// Сколько строк вернул источник всего (до фильтрации).
	RowsParsed int
	// Парные разряды: ожидаемый и нормальный отброс, борт источника — весь мир.
	RowsDoubles int
	// Строки, которые мы НЕ СМОГЛИ прочитать: нет id игрока, оба id совпали,
	// статус не распознан. Считается отдельно от парных не ради красоты:
	// «200 строк, все парные» и «200 строк, ни одну не разобрали» — разные
	// события, и Phase 7 по ним решает, срабатывает ли защита от пустого борта.
	// Скормите сюда борт upcoming вместо live — и разница станет видна сразу.
	RowsUnusable int
	// У источника есть ещё страницы. Каждая страница — ещё один запрос
	// из суточной квоты.
	HasMore bool
	// Нераспознанные значения event_status. Не ошибка разбора, но повод
	// залогировать: спека вендора дрейфует.
	UnknownEventStatuses []string
}

// FixturePage — разобранный борт предстоящих матчей.
type FixturePage struct {
	Fixtures    []Fixture
	RowsParsed  int
	RowsDoubles int
	// Отменённые и перенесённые: матч не состоится, окно опроса под него
	// открывать нельзя, а в Phase 8 из него получилась бы строка matches
	// про игру, которой не будет.
	RowsCancelled int
	RowsUnusable  int
	HasMore       bool
}

// Source — источник live-статусов. Интерфейс существует, чтобы смена вендора
// была новым файлом, а не переписыванием ingest'а.
// VendorPlayer — то немногое, что нам нужно об игроке у источника.
// Полей биографии здесь нет: сопоставлять их всё равно не с чем — birth_date и
// country_code у наших игроков пустые.
type VendorPlayer struct {
	Key  string
	Name string
}

type Source interface {
	Name() string
	PollLive(ctx context.Context) (Board, error)
	Fixtures(ctx context.Context, playerKeys []string) (FixturePage, error)
	// Player — карточка игрока по id источника. Стоит запрос из той же квоты,
	// поэтому вызывается только ленивым резолвером и только под лимитом.
	Player(ctx context.Context, key string) (VendorPlayer, error)
}
